package com.twinsoft.convertigo.engine.sqlcrud;

import java.sql.Connection;
import java.util.List;
import java.util.Properties;

/** HSQLDB tables of the SQL CRUD user interface tests: every family of type, keys, defaults and edge cases. */
final class MatrixTables {
	static final List<String> DDL = List.of(
			"""
			CREATE TABLE MATRIX (
				ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				"FirstName" VARCHAR(50) NOT NULL,
				NOTES CLOB,
				LONG_LABEL VARCHAR(1000),
				BIG BIGINT,
				PRICE DECIMAL(10,2) DEFAULT 0 NOT NULL,
				RATIO DOUBLE,
				ACTIVE BOOLEAN NOT NULL,
				BORN DATE,
				CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
				UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
				START_TIME TIME,
				PHOTO BLOB,
				CODE CHAR(3),
				STATUS VARCHAR(10) DEFAULT 'draft' NOT NULL,
				UID OTHER
			)""",
			"COMMENT ON COLUMN MATRIX.NOTES IS 'Free notes'",
			"CREATE TABLE PAIRS (A INTEGER NOT NULL, B VARCHAR(10) NOT NULL, V VARCHAR(20), PRIMARY KEY (A, B))",
			"CREATE TABLE LOGS (MSG VARCHAR(100), LOGGED_AT TIMESTAMP)",
			"CREATE TABLE ODD (ID INTEGER PRIMARY KEY, \"first name\" VARCHAR(20))");

	private MatrixTables() {
	}

	/** A new in-memory database with the tables. */
	static Connection open(String name) throws Exception {
		var info = new Properties();
		info.put("user", "SA");
		info.put("password", "");
		var connection = new org.hsqldb.jdbc.JDBCDriver().connect("jdbc:hsqldb:mem:" + name + System.nanoTime(), info);
		try (var st = connection.createStatement()) {
			for (var sql : DDL) {
				st.execute(sql);
			}
		}
		return connection;
	}
}
